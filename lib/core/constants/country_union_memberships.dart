Set<CountryUnion> countryUnionsForCountry(String? countryCode) {
  final normalized = countryCode?.trim().toUpperCase();
  if (normalized == null || normalized.isEmpty) return const {};
  return {
    if (euMemberCountryCodes.contains(normalized)) CountryUnion.eu,
    if (unMemberCountryCodes.contains(normalized)) CountryUnion.un,
  };
}

bool isCountryInUnion(String? countryCode, CountryUnion union) {
  final normalized = countryCode?.trim().toUpperCase();
  if (normalized == null || normalized.isEmpty) return false;
  return switch (union) {
    CountryUnion.eu => euMemberCountryCodes.contains(normalized),
    CountryUnion.un => unMemberCountryCodes.contains(normalized),
  };
}
